import test from 'node:test';
import assert from 'node:assert/strict';
import { access, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { preparePages } from '../../scripts/prepare-pages.mjs';

async function fixture(run) {
  const root = await mkdtemp(join(tmpdir(), 'velvet-pages-test-'));
  try {
    await mkdir(join(root, 'dist', 'ui'), { recursive: true });
    await writeFile(join(root, 'dist', 'index.html'), '<script type="module" src="./main.js"></script>');
    await writeFile(join(root, 'dist', 'main.js'), 'import "./ui/app.js";');
    await writeFile(join(root, 'dist', 'ui', 'app.js'), 'export const demo = true;');
    await writeFile(join(root, 'dist', 'styles.css'), 'body { color: #222; }');
    await run(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

test('prepara solo el build y .nojekyll, admite regeneración y conserva fuentes', async () => {
  await fixture(async root => {
    const first = await preparePages(root);
    assert.equal(first.length, 5);
    assert.equal(await readFile(join(root, 'docs', 'ui', 'app.js'), 'utf8'), 'export const demo = true;');
    assert.match(await readFile(join(root, 'docs', '.nojekyll'), 'utf8'), /Generated by Velvet/);
    await writeFile(join(root, 'dist', 'main.js'), 'export const updated = true;');
    assert.deepEqual(await preparePages(root), first);
    assert.equal(await readFile(join(root, 'docs', 'main.js'), 'utf8'), 'export const updated = true;');
    assert.equal(await readFile(join(root, 'dist', 'main.js'), 'utf8'), 'export const updated = true;');
  });
});

test('rechaza sobrescribir una carpeta docs sin el marcador propio', async () => {
  await fixture(async root => {
    await mkdir(join(root, 'docs'));
    await writeFile(join(root, 'docs', 'profesora.txt'), 'Conservar');
    await assert.rejects(preparePages(root), /Se conserva docs/);
    assert.equal(await readFile(join(root, 'docs', 'profesora.txt'), 'utf8'), 'Conservar');
  });
});

test('rechaza enlaces simbólicos sin copiar contenido externo', async () => {
  await fixture(async root => {
    await writeFile(join(root, 'private.js'), 'secreto ficticio de prueba');
    await symlink(join(root, 'private.js'), join(root, 'dist', 'external.js'));
    await assert.rejects(preparePages(root), /enlaces simbólicos/);
    await assert.rejects(access(join(root, 'docs')), { code: 'ENOENT' });
  });
});

test('rechaza recursos no permitidos sin crear docs', async () => {
  await fixture(async root => {
    await writeFile(join(root, 'dist', '.env'), 'dato ficticio que no debe publicarse');
    await assert.rejects(preparePages(root), /Recurso no admitido/);
    await assert.rejects(access(join(root, 'docs')), { code: 'ENOENT' });
  });
});
