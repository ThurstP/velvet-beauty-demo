import { access, copyFile, lstat, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const marker = 'Generated by Velvet scripts/prepare-pages.mjs. This directory contains build output only.\n';
const supported = new Set(['.html', '.css', '.js']);

async function filesIn(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = join(prefix, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`No se permiten enlaces simbólicos en dist: ${relative}`);
    if (entry.isDirectory()) files.push(...await filesIn(join(directory, entry.name), relative));
    else if (entry.isFile() && supported.has(extname(entry.name))) files.push(relative);
    else throw new Error(`Recurso no admitido para esta publicación estática: ${relative}`);
  }
  return files.sort();
}

/** Publish only self-contained compiled resources; never alter source files. */
export async function preparePages(projectRoot = fileURLToPath(new URL('../', import.meta.url))) {
  const root = resolve(projectRoot);
  const source = join(root, 'dist');
  const target = join(root, 'docs');
  const sourceInfo = await lstat(source);
  if (!sourceInfo.isDirectory() || sourceInfo.isSymbolicLink()) throw new Error('dist debe ser un directorio propio, sin enlaces simbólicos.');
  const files = await filesIn(source);
  if (!files.includes('index.html')) throw new Error('Primero genera dist/index.html con el build.');
  try {
    const info = await lstat(target);
    if (!info.isDirectory() || info.isSymbolicLink()) throw new Error('docs no es un directorio generado válido.');
    if (await readFile(join(target, '.nojekyll'), 'utf8') !== marker) throw new Error('docs no pertenece a esta herramienta.');
  } catch (error) {
    if (error.code !== 'ENOENT') throw new Error('Se conserva docs: no se sobrescriben documentos ajenos.', { cause: error });
    // A missing target is safe; an existing directory without the marker is not.
    try {
      await access(target);
      throw new Error('Se conserva docs: falta el marcador de contenido generado.');
    } catch (targetError) {
      if (targetError.code !== 'ENOENT') throw targetError;
    }
  }
  const staging = await mkdtemp(join(root, '.velvet-pages-'));
  try {
    for (const relative of files) {
      const destination = join(staging, relative);
      await mkdir(dirname(destination), { recursive: true });
      await copyFile(join(source, relative), destination);
    }
    await writeFile(join(staging, '.nojekyll'), marker);
    await rm(target, { recursive: true, force: true });
    await rename(staging, target);
  } catch (error) {
    await rm(staging, { recursive: true, force: true });
    throw error;
  }
  return files.map(relative => `docs/${relative}`).concat('docs/.nojekyll');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const files = await preparePages();
  console.log(`GitHub Pages: ${files.length} archivos preparados en docs/.`);
}
